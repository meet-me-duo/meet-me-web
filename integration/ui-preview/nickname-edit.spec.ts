import { expect, test } from "@playwright/test";

test("nickname editor opens from the account menu, supports keyboard editing, and saves only to synthetic API", async ({ page }, info) => {
  await page.setViewportSize(info.project.name === "desktop" ? { width: 1440, height: 1000 } : { width: 390, height: 844 });
  const external: string[] = [], errors: string[] = [], writes: string[] = [];
  page.on("request", request => { if (!request.url().startsWith("http://127.0.0.1:4175/")) external.push(request.url()); if (request.method() === "PUT") writes.push(request.postData() ?? ""); });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/__preview?scene=nickname_edit");
  const trigger = page.getByRole("button", { name: "서윤 계정 메뉴" });
  await trigger.click();
  await expect(page.getByRole("link", { name: "계정 보안" })).toHaveAttribute("href", "/account/security");
  await expect(page.getByRole("link", { name: "어드민 페이지" })).toHaveAttribute("href", "/operations");
  await page.screenshot({ path: info.outputPath("nickname-menu.png"), fullPage: true });
  await page.getByRole("button", { name: "닉네임 변경", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "닉네임 변경" });
  const input = dialog.getByRole("textbox", { name: "닉네임", exact: true });
  await expect(input).toHaveValue("서윤");
  await expect(input).toBeFocused();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeDisabled();
  await page.screenshot({ path: info.outputPath("nickname-dialog.png"), fullPage: false });
  await input.fill(" ");
  await expect(dialog.getByText("닉네임을 입력해 주세요.")).toBeVisible();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeDisabled();
  await input.fill("😀".repeat(50));
  await expect(dialog.getByText("50/50", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeEnabled();
  await input.fill("👩‍💻");
  await expect(dialog.getByText("3/50", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeEnabled();
  await input.fill("이름\u0085");
  await expect(dialog.getByText("사용할 수 없는 문자가 포함되어 있어요.")).toBeVisible();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeDisabled();
  await input.fill("가".repeat(51));
  await expect(dialog.getByText("닉네임은 50자까지 입력할 수 있어요.")).toBeVisible();
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeDisabled();
  await input.fill("새로운 서윤");
  const save = dialog.getByRole("button", { name: "저장", exact: true });
  await save.focus(); await page.keyboard.press("Tab");
  await expect(dialog.getByRole("button", { name: "닉네임 변경 닫기" })).toBeFocused();
  await page.keyboard.press("Shift+Tab"); await expect(save).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible(); await expect(trigger).toBeFocused();
  expect(writes).toEqual([]);
  await trigger.click(); await page.getByRole("button", { name: "닉네임 변경", exact: true }).click();
  await input.fill("새로운 서윤");
  await save.click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("button", { name: "새로운 서윤 계정 메뉴" })).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "닉네임을 변경했어요." })).toBeVisible();
  await page.screenshot({ path: info.outputPath("nickname-saved.png"), fullPage: true });
  expect(writes).toEqual([JSON.stringify({ displayName: "새로운 서윤" })]);
  expect(errors).toEqual([]); expect(external).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("nickname editor preserves input on error and makes pending submission and dismissal unambiguous", async ({ page }, info) => {
  await page.setViewportSize(info.project.name === "desktop" ? { width: 1440, height: 1000 } : { width: 390, height: 844 });
  await page.goto("/__preview?scene=nickname_error");
  await page.getByRole("button", { name: "서윤 계정 메뉴" }).click();
  await page.getByRole("button", { name: "닉네임 변경", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "닉네임 변경" });
  const input = dialog.getByRole("textbox", { name: "닉네임", exact: true });
  await input.fill("다른 닉네임");
  let release!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/auth/me", async route => { await held; await route.continue(); });
  await dialog.getByRole("button", { name: "저장", exact: true }).click();
  await expect(dialog).toHaveAttribute("aria-busy", "true");
  await expect(dialog.getByRole("button", { name: "저장 중…" })).toBeDisabled();
  await expect(dialog.getByRole("button", { name: "취소" })).toBeDisabled();
  await page.keyboard.press("Escape"); await expect(dialog).toBeVisible();
  release();
  await expect(dialog.getByRole("alert")).toHaveText("닉네임 저장을 확인하지 못했어요. 잠시 후 다시 시도해 주세요.");
  await expect(input).toHaveValue("다른 닉네임");
  await expect(dialog.getByRole("button", { name: "저장", exact: true })).toBeEnabled();
  await page.screenshot({ path: info.outputPath("nickname-error.png"), fullPage: false });
  await dialog.getByRole("button", { name: "취소" }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("button", { name: "서윤 계정 메뉴" })).toBeFocused();
});

test("confirmed nickname save with failed session refresh asks for login instead of reporting an unsaved name", async ({ page }) => {
  await page.goto("/__preview?scene=nickname_edit");
  await page.getByRole("button", { name: "서윤 계정 메뉴" }).click();
  await page.getByRole("button", { name: "닉네임 변경", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "닉네임 변경" });
  await dialog.getByRole("textbox", { name: "닉네임", exact: true }).fill("수정한 서윤");
  let refreshes = 0;
  await page.route("**/api/auth/refresh", route => { refreshes++; return route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ code: "AUTH_UNAVAILABLE" }) }); });
  await dialog.getByRole("button", { name: "저장", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "닉네임은 저장됐어요. 로그인 상태를 다시 확인해 주세요." })).toBeVisible();
  await expect(page.getByRole("link", { name: "로그인", exact: true })).toBeFocused();
  expect(refreshes).toBe(1);
});
